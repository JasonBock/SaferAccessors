using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using NUnit.Framework;
using SaferAccessors.Tests;

namespace SaferAccessors.Analysis.Tests;

internal static class SaferAccessorsGeneratorTests
{
	[Test]
	public static async Task GenerateWithReferencedAssemblyAsync()
	{
		var source =
			"""
			public class Holder
			{
				private int id;

				private Holder() { }

				private void ProcessData(string data) { }

				private string Data { get; set; }
			}
			""";

		var sourceReferences = Shared.References.Value
			 .Cast<MetadataReference>();
		var sourceSyntaxTree = CSharpSyntaxTree.ParseText(source);
		var sourceCompilation = CSharpCompilation.Create("Source", [sourceSyntaxTree],
			 sourceReferences,
			 new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

		using var outputStream = new MemoryStream();
		var result = sourceCompilation.Emit(outputStream);
		outputStream.Position = 0;
		var outputReference = MetadataReference.CreateFromStream(outputStream);

		var code =
			"""
			using SaferAccessors;

			[assembly: UnsafeAccessorMap(typeof(Holder))]
			""";

		var generatedCode =
			"""
			// <auto-generated/>
			
			#nullable enable
			
			public static partial class HolderExtensions
			{
				extension(global::Holder self)
				{
					public int id
					{
						get => HolderAccessors.id(self);
						set => HolderAccessors.id(self) = value;
					}
				}
				
				private static partial class HolderAccessors
				{
					[global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.Field, Name = "id")]
					public static extern ref int id(global::Holder self);
				}
				
				extension(global::Holder)
				{
					[global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.Constructor)]
					public extern static global::Holder New();
				}
				
				extension(global::Holder self)
				{
					[global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.Method, Name = "ProcessData")]
					public extern void ProcessData(string data);
				}
				
				extension(global::Holder self)
				{
					public string Data
					{
						get => HolderAccessors.GetData(self);
						set => HolderAccessors.SetData(self, value);
					}
				}
				
				private static partial class HolderAccessors
				{
					[global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.Method, Name = "get_Data")]
					public static extern string GetData(global::Holder self);
					
					[global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.Method, Name = "set_Data")]
					public static extern void SetData(global::Holder self, string value);
					
				}
				
			}
			
			""";

		await TestAssistants.RunGeneratorAsync<SaferAccessorsGenerator>(code,
			[($"Holder_Accessors.g.cs", generatedCode)],
			[],
			additionalReferences: sourceReferences.Append(outputReference));
	}

